// Command gen writes presets_gen.go from the site's preset roster list (site/src/data/rosters.ts), so the CLI ships
// exactly the rosters the site shows.
//
// Usage: go run ./gen <rosters.ts> <output.go>
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"regexp"
	"strings"

	"github.com/piazzatron/rostr/cli/internal/presets"
	"github.com/piazzatron/rostr/cli/internal/roster"
)

func main() {
	if len(os.Args) != 3 {
		fmt.Fprintln(os.Stderr, "usage: gen <rosters.ts> <output.go>")
		os.Exit(2)
	}
	source, err := os.ReadFile(os.Args[1])
	if err != nil {
		fail(err)
	}
	parsed, err := ParseRostersTS(string(source))
	if err != nil {
		fail(err)
	}
	if err := os.WriteFile(os.Args[2], render(parsed), 0o644); err != nil {
		fail(err)
	}
}

var (
	presetPattern = regexp.MustCompile(`(?s)emoji:\s*"([^"]*)",\s*id:\s*"([^"]*)",\s*name:\s*"([^"]*)",\s*` +
		`source:\s*"([^"]*)",.*?members:\s*\[([^\]]*)\]`)
	idPattern     = regexp.MustCompile(`\bid:\s*"`)
	stringPattern = regexp.MustCompile(`"([^"]*)"`)
)

// ParseRostersTS reads the preset list out of rosters.ts. It relies on the file's fixed field order (emoji, id,
// name, source, ..., members) and fails if it finds a different number of presets than `id:` fields.
func ParseRostersTS(source string) ([]presets.Preset, error) {
	var out []presets.Preset
	for _, m := range presetPattern.FindAllStringSubmatch(source, -1) {
		out = append(out, presets.Preset{
			Emoji:   m[1],
			ID:      m[2],
			Name:    m[3],
			Source:  m[4],
			Members: parseMembers(m[5]),
		})
	}
	if want := len(idPattern.FindAllString(source, -1)); len(out) != want || want == 0 {
		return nil, fmt.Errorf("parsed %d presets but found %d ids; has rosters.ts changed shape?", len(out), want)
	}
	return out, nil
}

func parseMembers(list string) []roster.Member {
	members := []roster.Member{}
	for _, m := range stringPattern.FindAllStringSubmatch(list, -1) {
		members = append(members, roster.ParseMember(m[1]))
	}
	return members
}

func render(all []presets.Preset) []byte {
	var b bytes.Buffer
	b.WriteString("// Code generated by go run ./gen from site/src/data/rosters.ts; DO NOT EDIT.\n\n")
	b.WriteString("package presets\n\nimport \"github.com/piazzatron/rostr/cli/internal/roster\"\n\n")
	b.WriteString("var all = []Preset{\n")
	for _, p := range all {
		fmt.Fprintf(&b, "{\nID: %q,\nName: %q,\nSource: %q,\nEmoji: %q,\n", p.ID, p.Name, p.Source, p.Emoji)
		fmt.Fprintf(&b, "Members: %s,\n},\n", renderMembers(p.Members))
	}
	b.WriteString("}\n")

	formatted, err := format.Source(b.Bytes())
	if err != nil {
		fail(err)
	}
	return formatted
}

func renderMembers(members []roster.Member) string {
	parts := make([]string, len(members))
	for i, m := range members {
		parts[i] = fmt.Sprintf("{Name: %q, Emoji: %q}", m.Name, m.Emoji)
	}
	return "[]roster.Member{\n" + strings.Join(parts, ",\n") + ",\n}"
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, "gen:", err)
	os.Exit(1)
}
